// Builds the data the Go and Python servers share with the TypeScript reference: the action table (schemas,
// descriptions, flags), the document and transaction JSON Schemas, the report templates, the HTTP route table and the
// OpenAPI document. The servers embed this file instead of retyping it, so the contract has one author.
//
// Templates are rendered once with sentinel values and substituted at run time:
//   PREFIX_SENTINEL  stands for the idPrefix, SUBJECT_SENTINEL for the cleaned subject; top-level blocks carry parentId
//   null (the caller's parentId replaces it). `withSubject` is the template for a non-empty subject, `withoutSubject`
//   the one with the neutral placeholder wording.
import { AGENT_ACTIONS, LIMITS, TEMPLATE_KINDS, TRANSPORT_LIMITS, createTemplate, documentSchema, listTemplates, templateTitle, transactionSchema } from '../packages/core/src/index.js';
import { ROUTES } from '../backends/typescript/api/src/routes.js';
import { createOpenApiDocument } from '../backends/typescript/api/src/openapi.js';

export const SPEC_COPIES = ['conformance/server-spec.v1.json', 'backends/go/server/spec.json', 'backends/python/src/super_editor/server_spec.json'];
export const PREFIX_SENTINEL = 'ZZPFXZZ';
export const SUBJECT_SENTINEL = 'ZZSUBJZZ';

export function buildServerSpec(): Record<string, unknown> {
  const templates = Object.fromEntries(TEMPLATE_KINDS.map(kind => [kind, {
    withSubject: createTemplate(kind, { idPrefix: PREFIX_SENTINEL, subject: SUBJECT_SENTINEL }),
    withoutSubject: createTemplate(kind, { idPrefix: PREFIX_SENTINEL }),
  }]));
  // Self-check: substituting a real prefix and subject into the sentinel form must give what the reference gives.
  for (const kind of TEMPLATE_KINDS) {
    const substitute = (value: unknown, prefix: string, subject: string): unknown => {
      if (typeof value === 'string') return value.split(PREFIX_SENTINEL).join(prefix).split(SUBJECT_SENTINEL).join(subject);
      if (Array.isArray(value)) return value.map(entry => substitute(entry, prefix, subject));
      if (value !== null && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, substitute(entry, prefix, subject)]));
      return value;
    };
    const entry = templates[kind]!;
    const a = JSON.stringify(substitute(entry.withSubject, 'p.q-1', 'AAPL "x" \\ y'));
    const b = JSON.stringify(createTemplate(kind, { idPrefix: 'p.q-1', subject: 'AAPL "x" \\ y' }));
    if (a !== b) throw new Error(`template ${kind}: sentinel form drifted from the reference`);
    const c = JSON.stringify(substitute(entry.withoutSubject, 'k', ''));
    if (c !== JSON.stringify(createTemplate(kind, { idPrefix: 'k' }))) throw new Error(`template ${kind}: placeholder form drifted`);
  }
  return {
    version: 1,
    note: 'Generated by scripts/export-server-spec.ts from the TypeScript reference. The Go and Python servers embed this file.',
    limits: { ...TRANSPORT_LIMITS, blocksPerOperation: LIMITS.blocksPerOperation, operations: LIMITS.operations, depth: LIMITS.depth, blocks: LIMITS.blocks, citations: LIMITS.citations, text: LIMITS.text, searchText: LIMITS.searchText, title: LIMITS.title },
    templateKinds: [...TEMPLATE_KINDS],
    templateInfos: listTemplates(),
    templateTitles: Object.fromEntries(TEMPLATE_KINDS.map(kind => [kind, templateTitle(kind)])),
    templates,
    actions: AGENT_ACTIONS.map(({ name, title, description, access, destructive, idempotent, inputSchema, textField }) => ({ name, title, description, access, destructive, idempotent, inputSchema, ...(textField ? { textField } : {}) })),
    documentSchema,
    transactionSchema,
    routes: ROUTES.map(({ run: _run, ...route }) => route),
    openapi: createOpenApiDocument(),
  };
}
