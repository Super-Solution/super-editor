import { pathProblem, writeZip, ZipError, type WriteZipOptions } from './zip.js';
import { escapeXmlAttribute } from './xml.js';

/** Relationship types every Office Open XML package uses. Format packages add their own (styles, numbering, …). */
export const RELATIONSHIP_TYPES = {
  officeDocument: 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument',
  coreProperties: 'http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties',
  extendedProperties: 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/extended-properties',
  hyperlink: 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink',
} as const;

export type RelationshipInput =
  /** Points at another part of this package. `part` is its path, for example `word/styles.xml`. */
  | { type: string; part: string }
  /** Points outside the package. `url` is written as given; the caller checks that it is safe to link. */
  | { type: string; url: string };

export interface OpcPackage {
  /** Adds a part. `path` is the part name without the leading slash. `[Content_Types].xml` and `_rels/…` are generated and can not be added. */
  addPart(path: string, contentType: string, data: string | Uint8Array): void;
  /** Adds a relationship from a part (or from the package itself with `null`) and returns its id (`rId1`, `rId2`, …, per source). */
  addRelationship(source: string | null, relationship: RelationshipInput): string;
  /** The ZIP bytes. Throws a `ZipError` for an invalid package (a relationship to a part that does not exist, a bad content type). */
  toBytes(options?: WriteZipOptions): Promise<Uint8Array>;
}

const relsPath = (source: string | null): string => source === null ? '_rels/.rels' : `${source.slice(0, source.lastIndexOf('/') + 1)}_rels/${source.slice(source.lastIndexOf('/') + 1)}.rels`;
function relativeTarget(source: string | null, part: string): string {
  const from = source === null ? [] : source.split('/').slice(0, -1), to = part.split('/');
  let shared = 0;
  while (shared < from.length && shared < to.length - 1 && from[shared] === to[shared]) shared++;
  return [...from.slice(shared).map(() => '..'), ...to.slice(shared)].join('/');
}
const CONTENT_TYPE = /^[A-Za-z0-9!#$&^_.+-]+\/[A-Za-z0-9!#$&^_.+-]+(?:;\s*[A-Za-z0-9-]+=[A-Za-z0-9._-]+)*$/;

/** A package under construction: parts with content types, and the relationships between them. Nothing is written until `toBytes`. */
export function createPackage(): OpcPackage {
  const parts = new Map<string, { contentType: string; data: string | Uint8Array }>(), seen = new Set<string>();
  const relationships = new Map<string | null, { id: string; type: string; target: string; external: boolean; part?: string }[]>();
  return {
    addPart(path, contentType, data) {
      const problem = pathProblem(path);
      if (problem) throw new ZipError('unsafe-path', `${problem} Got "${path}".`);
      if (path === '[Content_Types].xml' || path.toLowerCase().startsWith('_rels/') || path.toLowerCase().includes('/_rels/')) throw new ZipError('invalid-input', `"${path}" is generated by the package and can not be added as a part.`);
      if (!CONTENT_TYPE.test(contentType)) throw new ZipError('invalid-input', `"${contentType}" is not a valid content type.`);
      const key = path.toLowerCase();
      if (seen.has(key)) throw new ZipError('duplicate', `A part named "${path}" already exists (part names are compared without regard to case).`);
      seen.add(key); parts.set(path, { contentType, data });
    },
    addRelationship(source, relationship) {
      if (source !== null && !parts.has(source)) throw new ZipError('invalid-input', `Add the part "${source}" before adding relationships from it.`);
      const list = relationships.get(source) ?? [], id = `rId${list.length + 1}`;
      list.push('part' in relationship
        ? { id, type: relationship.type, target: relativeTarget(source, relationship.part), external: false, part: relationship.part }
        : { id, type: relationship.type, target: relationship.url, external: true });
      relationships.set(source, list);
      return id;
    },
    async toBytes(options) {
      const defaults = '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>';
      const overrides = [...parts].map(([path, { contentType }]) => `<Override PartName="/${escapeXmlAttribute(path)}" ContentType="${escapeXmlAttribute(contentType)}"/>`).join('');
      const header = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n';
      const entries: { path: string; data: string | Uint8Array }[] = [{ path: '[Content_Types].xml', data: `${header}<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">${defaults}${overrides}</Types>` }];
      const rels = [...relationships].map(([source, list]) => {
        for (const rel of list) if (!rel.external && !parts.has(rel.part!)) throw new ZipError('invalid-input', `A relationship (${rel.id}) points at the part "${rel.part}", which does not exist.`);
        return { path: relsPath(source), data: `${header}<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${list.map(rel => `<Relationship Id="${rel.id}" Type="${escapeXmlAttribute(rel.type)}" Target="${escapeXmlAttribute(rel.target)}"${rel.external ? ' TargetMode="External"' : ''}/>`).join('')}</Relationships>` };
      });
      // [Content_Types].xml first, then the package relationships, then the rest: the order Word itself writes.
      entries.push(...rels.filter(rel => rel.path === '_rels/.rels'), ...[...parts].map(([path, { data }]) => ({ path, data })), ...rels.filter(rel => rel.path !== '_rels/.rels'));
      return writeZip(entries, options);
    },
  };
}
