package validation

import (
	"encoding/json"
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

type conformanceCase struct {
	Kind        string          `json:"kind"`
	Input       json.RawMessage `json:"input"`
	PortRejects bool            `json:"portRejects"`
	Expect      struct {
		OK     bool             `json:"ok"`
		Value  any              `json:"value"`
		Issues []map[string]any `json:"issues"`
	} `json:"expect"`
}

// roundTrip turns validator output into what JSON would carry, so it compares with the file's values.
func roundTrip(t *testing.T, v any) any {
	t.Helper()
	raw, err := json.Marshal(Plain(v))
	if err != nil {
		t.Fatal(err)
	}
	var out any
	if err := json.Unmarshal(raw, &out); err != nil {
		t.Fatal(err)
	}
	return out
}

func issueMap(i Issue) map[string]any {
	m := map[string]any{"code": i.Code, "message": i.Message}
	if i.Path != "" {
		m["path"] = i.Path
	}
	if i.Hint != "" {
		m["hint"] = i.Hint
	}
	return m
}

// TestConformance replays every case of conformance/validation.v1.json, generated by the TypeScript validators.
func TestConformance(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("..", "..", "..", "conformance", "validation.v1.json"))
	if err != nil {
		t.Fatal(err)
	}
	var data struct {
		Cases []conformanceCase `json:"cases"`
	}
	if err := json.Unmarshal(raw, &data); err != nil {
		t.Fatal(err)
	}
	if len(data.Cases) < 1000 {
		t.Fatalf("only %d cases", len(data.Cases))
	}
	for i, c := range data.Cases {
		input, err := Decode(c.Input)
		if err != nil {
			t.Fatalf("case %d: %v", i, err)
		}
		if c.Kind == "url" {
			got, ok := SafeURL(input, false)
			if c.PortRejects || !c.Expect.OK {
				if ok {
					t.Errorf("case %d: %q should be refused, got %q", i, input, got)
				}
			} else if !ok || got != c.Expect.Value {
				t.Errorf("case %d: %q = %q (%v), want %v", i, input, got, ok, c.Expect.Value)
			}
			continue
		}
		var res Result
		switch c.Kind {
		case "document":
			res = ValidateDocument(input)
		case "transaction":
			res = ValidateTransaction(input)
		case "actor":
			res = ReadActor(input)
		case "timestamp":
			res = Timestamp(input)
		default:
			t.Fatalf("case %d: unknown kind %q", i, c.Kind)
		}
		if res.OK != c.Expect.OK {
			t.Errorf("case %d (%s): ok = %v, want %v; issues %v", i, c.Kind, res.OK, c.Expect.OK, res.Issues)
			continue
		}
		if res.OK {
			if got := roundTrip(t, res.Value); !reflect.DeepEqual(got, c.Expect.Value) {
				t.Errorf("case %d (%s): value differs\n got  %v\n want %v", i, c.Kind, got, c.Expect.Value)
			}
			continue
		}
		issues := make([]map[string]any, len(res.Issues))
		for j, is := range res.Issues {
			issues[j] = issueMap(is)
		}
		if !reflect.DeepEqual(issues, c.Expect.Issues) {
			t.Errorf("case %d (%s): issues\n got  %v\n want %v", i, c.Kind, issues, c.Expect.Issues)
		}
	}
}
