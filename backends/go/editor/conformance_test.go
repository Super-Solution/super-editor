package editor

import (
	"encoding/json"
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/Super-Solution/super-editor/backends/go/validation"
)

type scenarioFile struct {
	Scenarios []struct {
		Scenario struct {
			Name         string          `json:"name"`
			Initial      json.RawMessage `json:"initial"`
			HistoryLimit *int            `json:"historyLimit"`
			Revisions    []any           `json:"revisions"`
			Final        any             `json:"final"`
		} `json:"scenario"`
		Steps []struct {
			Action string          `json:"action"`
			Now    string          `json:"now"`
			Input  json.RawMessage `json:"input"`
			Expect struct {
				OK              bool    `json:"ok"`
				Duplicate       bool    `json:"duplicate"`
				Document        any     `json:"document"`
				Revision        any     `json:"revision"`
				Issues          []Issue `json:"issues"`
				CurrentRevision float64 `json:"currentRevision"`
			} `json:"expect"`
		} `json:"steps"`
	} `json:"scenarios"`
}

// jsonValue turns a result into what JSON carries, for comparison with the file.
func jsonValue(t *testing.T, v any) any {
	t.Helper()
	raw, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	var out any
	if err := json.Unmarshal(raw, &out); err != nil {
		t.Fatal(err)
	}
	return out
}

// TestConformance replays every scenario of conformance/editor.v1.json, generated by the TypeScript editor.
func TestConformance(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("..", "..", "..", "conformance", "editor.v1.json"))
	if err != nil {
		t.Fatal(err)
	}
	var data scenarioFile
	if err := json.Unmarshal(raw, &data); err != nil {
		t.Fatal(err)
	}
	steps := 0
	for _, entry := range data.Scenarios {
		sc := entry.Scenario
		initial, err := validation.Decode(sc.Initial)
		if err != nil {
			t.Fatal(err)
		}
		clock := ""
		ed, err := New(initial, Options{Now: func() string { return clock }, HistoryLimit: sc.HistoryLimit})
		if err != nil {
			t.Fatalf("%s: %v", sc.Name, err)
		}
		for i, step := range entry.Steps {
			clock = step.Now
			input, err := validation.Decode(step.Input)
			if err != nil {
				t.Fatal(err)
			}
			var res Result
			switch step.Action {
			case "apply":
				res = ed.Apply(input)
			case "undo", "redo":
				obj := input.(*validation.Object)
				if step.Action == "undo" {
					res = ed.Undo(obj.Values["actor"], obj.Values["expectedRevision"])
				} else {
					res = ed.Redo(obj.Values["actor"], obj.Values["expectedRevision"])
				}
			default:
				t.Fatalf("unknown action %q", step.Action)
			}
			label := sc.Name + " step " + itoa(i)
			steps++
			if res.OK != step.Expect.OK {
				t.Errorf("%s: ok = %v, want %v; issues %v", label, res.OK, step.Expect.OK, res.Issues)
				continue
			}
			if res.OK {
				if res.Duplicate != step.Expect.Duplicate {
					t.Errorf("%s: duplicate = %v", label, res.Duplicate)
				}
				if got := jsonValue(t, res.Document); !reflect.DeepEqual(got, step.Expect.Document) {
					t.Errorf("%s: document differs\n got  %s\n want %s", label, mustJSON(got), mustJSON(step.Expect.Document))
				}
				if got := jsonValue(t, res.Revision); !reflect.DeepEqual(got, step.Expect.Revision) {
					t.Errorf("%s: revision differs\n got  %s\n want %s", label, mustJSON(got), mustJSON(step.Expect.Revision))
				}
				continue
			}
			if !reflect.DeepEqual(res.Issues, step.Expect.Issues) {
				t.Errorf("%s: issues\n got  %+v\n want %+v", label, res.Issues, step.Expect.Issues)
			}
			if res.CurrentRevision != step.Expect.CurrentRevision {
				t.Errorf("%s: currentRevision = %v, want %v", label, res.CurrentRevision, step.Expect.CurrentRevision)
			}
		}
		revisions := []any{}
		for _, r := range ed.Revisions() {
			revisions = append(revisions, r)
		}
		if got := jsonValue(t, revisions); !reflect.DeepEqual(got, jsonValue(t, sc.Revisions)) {
			t.Errorf("%s: revision log differs\n got  %s\n want %s", sc.Name, mustJSON(got), mustJSON(sc.Revisions))
		}
		if got := jsonValue(t, ed.Snapshot()); !reflect.DeepEqual(got, jsonValue(t, sc.Final)) {
			t.Errorf("%s: final document differs", sc.Name)
		}
	}
	if steps < 1000 {
		t.Fatalf("only %d steps", steps)
	}
}

func mustJSON(v any) string {
	raw, _ := json.Marshal(v)
	if len(raw) > 3000 {
		return string(raw[:3000]) + "..."
	}
	return string(raw)
}

func itoa(i int) string {
	raw, _ := json.Marshal(i)
	return string(raw)
}
